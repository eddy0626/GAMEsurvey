# -*- coding: utf-8 -*-
"""파이썬 집계가 수작업 리포트의 수치를 그대로 내는지 확인.

test/run.js 와 같은 기준선(참조/미스트월드_플레이테스트_결과리포트.docx)을 쓴다.
JS 와 파이썬 두 구현이 같은 답을 내야 어느 쪽으로 리포트를 만들든 수치가 같다.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from py import config as C
from py.ingest import 파싱, 명부적용
from py.aggregate import 게임집계, 찾기, 문항찾기

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fx = json.load(open(os.path.join(ROOT, "test", "fixture_mistworld.json"), encoding="utf-8"))

통과 = 실패 = 0
실패목록 = []
def eq(라벨, 실제, 기대):
    global 통과, 실패
    ok = str(실제) == str(기대)
    if ok: 통과 += 1
    else:
        실패 += 1; 실패목록.append(f"{라벨} — 기대 {기대} / 실제 {실제}")
    print(f"  {'OK ' if ok else 'NG '} {라벨:<44} {str(실제):>10}  (기대 {기대})")
def 절(t): print(f"\n── {t} " + "─" * max(0, 56 - len(t)))

게임 = C.게임찾기("G01")
응답, 맵 = 파싱(fx["헤더"], fx["행"], 게임)
명부 = {__import__("py.ingest", fromlist=["이름키"]).이름키(n): dict(이름=n, ID=i, 유형=t)
        for n, i, t, _ in fx["명부"]}
명부적용(응답, 명부)
A = 게임집계(응답, 게임)
m = A["지표"]

절("헤더 매핑 · 파싱")
eq("공통 문항 누락", len(맵["누락"]), 0)
eq("고유 문항 수", len(맵["고유"]), 10)
eq("응답 건수", m["N"], 15)
eq("첫 응답자 ID", 응답[0].ID, "P01")

절("2-1 표 — 8개 항목")
기대 = [("재미",3.67,0.98,9,2),("조작성",2.93,1.03,5,4),("그래픽 · 아트",4.40,0.63,14,0),
        ("몰입도",3.73,1.10,10,3),("완성도",2.53,0.92,2,7),("정식 출시 기대감",3.20,1.26,7,4),
        ("진행 흐름",2.73,1.03,4,6),("기술 안정성",3.87,0.64,11,0)]
for a, (이름, 평균, 편차, 긍, 부) in zip(m["육각"] + m["추가"], 기대):
    eq(f"{이름} 평균", f'{a["평균"]:.2f}', f"{평균:.2f}")
    eq(f"{이름} 표준편차", f'{a["표준편차"]:.2f}', f"{편차:.2f}")
    eq(f"{이름} 긍정", a["긍정"], 긍)
    eq(f"{이름} 부정", a["부정"], 부)
eq("6축 총평균", f'{m["육각총평균"]:.2f}', "3.41")
eq("최고 항목", f'{m["최고축"]["이름"]} {m["최고축"]["평균"]:.2f}', "그래픽 · 아트 4.40")
eq("최저 항목", f'{m["최저축"]["이름"]} {m["최저축"]["평균"]:.2f}', "완성도 2.53")

절("2-3 NPS · 2-4 적정가격 · 2-2 진행도")
eq("NPS", m["NPS"]["값"], -33)
eq("추천/중립/비추천", f'{m["NPS"]["추천"]}/{m["NPS"]["중립"]}/{m["NPS"]["비추천"]}', "2/6/7")
eq("비율", f'{m["NPS"]["추천율"]}/{m["NPS"]["중립율"]}/{m["NPS"]["비추천율"]}', "13/40/47")
for 답, 인, 비 in [("5,000원 미만",2,13),("5,000~9,900원",1,7),("10,000~14,900원",6,40),
                   ("15,000~19,900원",4,27),("20,000~29,900원",2,13),("30,000원 이상",0,0)]:
    x = 찾기(m["적정가격"], 답); eq(f"적정가 {답}", f'{x["인원"]}명 {x["비율"]}%', f"{인}명 {비}%")
eq("본편 미도달", f'{m["진행도정체"]["인원"]}명 {m["진행도정체"]["비율"]}%', "5명 33%")
eq("유료 고려 비율", m["유료고려"]["비율"], 87)
eq("구매 의향 비율", m["구매의향률"]["비율"], 53)

절("1장 표본 · 응답률")
eq("연령대", " · ".join(f'{v["답"]} {v["인원"]}명' for v in m["연령대"]),
   "20대 9명 · 30대 3명 · 10대 2명 · 40대 이상 1명")
eq("성별", " · ".join(f'{v["답"]} {v["인원"]}명' for v in m["성별"]), "남성 9명 · 여성 6명")
eq("장르 상위4", " · ".join(f'{v["답"]} {v["인원"]}명' for v in m["선호장르"][:4]),
   "RPG 9명 · 전략 · 턴제 6명 · 퍼즐 3명 · 로그라이크 · 로그라이트 3명")
eq("개선점 건수", m["응답률"]["개선점"], 14)
eq("개발팀 메시지", m["응답률"]["개발팀메시지"], 13)
eq("버그 상황", m["응답률"]["버그상황"], 5)

절("부록 A — 문항별 집계")
표 = [("조작법 튜토리얼","객관식",[("쉬웠다",5,33),("어려웠다",5,33),("보통이다",5,33)]),
      ("전투 시스템은","객관식",[("어려웠다",7,47),("보통이다",5,33),("쉬웠다",3,20)]),
      ("스토리에 대해","체크박스",[("몰입이 잘 되었다",6,40),("텍스트가 과도하다",5,33),("스토리는 평이했다",1,7)]),
      ("주사위 시스템에","체크박스",[("이해하기 어려웠다",6,40),("D&D 방식의 주사위였으면 좋겠다",4,27)]),
      ("선택한 직업","객관식",[("주술사",5,33),("백기사",5,33),("사제",3,20)]),
      ("버그 경험","객관식",[("겪지 않았다",9,60),("있었고 플레이에 지장이 있었다",2,13)])]
for 부분, 유형, 행들 in 표:
    항 = 문항찾기(A["문항집계"], 부분)
    eq(f"{부분} 유형", 항["유형"], 유형)
    for 답, 인, 비 in 행들:
        x = 찾기(항["집계"], 답); eq(f"  {부분} · {답}", f'{x["인원"]}명 {x["비율"]}%', f"{인}명 {비}%")
eq("불합리(고유 서술형) 건수", len(문항찾기(A["문항집계"], "불합리하다고")["서술"]), 8)

절("4장 세그먼트")
장르 = A["세그먼트"]["장르"]
eq("RPG·전략 인원/6축/NPS/흐름/정체",
   f'{장르[0]["인원"]}/{장르[0]["육각평균"]:.2f}/{장르[0]["NPS평균"]:.1f}/{장르[0]["진행흐름"]:.2f}/{장르[0]["정체"]}',
   "10/3.78/7.6/3.00/2")
eq("그 외 인원/6축/NPS/흐름/정체",
   f'{장르[1]["인원"]}/{장르[1]["육각평균"]:.2f}/{장르[1]["NPS평균"]:.1f}/{장르[1]["진행흐름"]:.2f}/{장르[1]["정체"]}',
   "5/2.67/4.2/2.20/3")
튜 = {r["라벨"]: r for r in A["세그먼트"]["튜토리얼"]["행"]}
for t, n, hx, nps, fl, ex in [("쉬웠다",5,"3.97","8.0","3.40","3.80"),
                              ("보통이다",5,"3.60","7.2","2.60","3.80"),
                              ("어려웠다",5,"2.67","4.2","2.20","2.00")]:
    g = 튜[f"튜토리얼 '{t}'"]
    eq(f"튜토리얼 '{t}'",
       f'{g["인원"]}/{g["육각평균"]:.2f}/{g["NPS평균"]:.1f}/{g["진행흐름"]:.2f}/{g["출시기대감"]:.2f}',
       f"{n}/{hx}/{nps}/{fl}/{ex}")

절("이슈 플래그")
