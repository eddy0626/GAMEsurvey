from collections import Counter
c = Counter(f["심각도"] for f in F)
print(f'     Critical {c["Critical"]} · High {c["High"]} · 검토필요 {c["검토필요"]} · 강점 {c["강점"]}  (합계 {len(F)})')
def 있나(규, 부분): return any(f["규칙"] == 규 and 부분 in (f["제목"] + f["근거"]) for f in F)
eq("튜토리얼 33% Critical", 있나("튜토리얼", "33%"), True)
eq("진행도 정체 33% Critical", 있나("진행도", "33%"), True)
eq("완성도 6축평균", 있나("6축평균", "완성도"), True)
eq("그래픽 강점", 있나("강점", "그래픽 · 아트"), True)
eq("출시기대감 검토필요", 있나("표준편차", "정식 출시 기대감"), True)
eq("튜토리얼 문항 중복 없음",
   sum(1 for f in F if f["규칙"] == "부정선택지" and "조작법 튜토리얼" in f["제목"]), 0)

print("\n" + "═" * 74)
print(f"  통과 {통과} · 실패 {실패}")
