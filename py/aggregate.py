def 세그요약(라벨, 그룹):
    if not 그룹:
        return dict(라벨=라벨, 인원=0, 육각평균=None, NPS평균=None,
                    진행흐름=None, 출시기대감=None, 정체=0)
    개인 = [mean([v for v in r.육각 if isinstance(v, (int, float))])
            for r in 그룹 if any(isinstance(v, (int, float)) for v in r.육각)]
    nps = [r.추천의향 for r in 그룹 if isinstance(r.추천의향, (int, float))]
    flow = [r.진행흐름 for r in 그룹 if isinstance(r.진행흐름, (int, float))]
    기대 = [r.육각[5] for r in 그룹 if isinstance(r.육각[5], (int, float))]
    return dict(라벨=라벨, 인원=len(그룹),
                육각평균=반올림(mean(개인), 2) if 개인 else None,
                NPS평균=반올림(mean(nps), 1) if nps else None,
                진행흐름=반올림(mean(flow), 2) if flow else None,
                출시기대감=반올림(mean(기대), 2) if 기대 else None,
                정체=sum(1 for r in 그룹 if r.진행도 in C.진행도_정체단계))


def 세그먼트(응답목록, 게임):
    코드 = 게임["코드"]
    코어장르 = C.게임_코어장르.get(코드, [])
    코어 = [r for r in 응답목록 if any(g in r.선호장르 for g in 코어장르)]
    비코어 = [r for r in 응답목록 if r not in 코어]

    결과 = dict(코어장르=코어장르,
                장르=[세그요약(" · ".join(코어장르) + " 선호", 코어),
                      세그요약("그 외 장르 선호", 비코어)],
                튜토리얼=None, 진행=None)

    튜 = C.게임_튜토리얼문항.get(코드)
    if 튜 and 응답목록:
        정규문항 = 정규화(튜["문항"])
        열 = next((i for i, d in enumerate(응답목록[0].고유) if d["문항"] == 정규문항), -1)
        if 열 >= 0:
            그룹 = {}
            for r in 응답목록:
                그룹.setdefault(r.고유[열]["답"] or "(무응답)", []).append(r)
            순서 = sorted(그룹, key=lambda k: -len(그룹[k]))
            결과["튜토리얼"] = dict(문항=정규문항,
                                    행=[세그요약(f"튜토리얼 '{k}'", 그룹[k]) for k in 순서])

    도달 = [r for r in 응답목록 if r.진행도 not in C.진행도_정체단계]
    미도달 = [r for r in 응답목록 if r.진행도 in C.진행도_정체단계]
    결과["진행"] = [세그요약("본편 진입", 도달), 세그요약("튜토리얼 단계 정체", 미도달)]
    return 결과


