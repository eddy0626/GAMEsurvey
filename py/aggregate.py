def 지표계산(응답목록):
    N = len(응답목록)
    육각 = [축통계([r.육각[i] for r in 응답목록], 이름)
            for i, (_, 이름) in enumerate(C.육각축)]
    추가 = [축통계([getattr(r, 키) for r in 응답목록], 이름) for 키, 이름 in C.추가축]

    축평균 = [a["평균원값"] for a in 육각 if a["평균원값"] is not None]
    육각총평균 = mean(축평균) if 축평균 else None

    nps = [r.추천의향 for r in 응답목록 if isinstance(r.추천의향, (int, float))]
    추천 = sum(1 for v in nps if v >= 9)
    중립 = sum(1 for v in nps if 7 <= v <= 8)
    비추천 = sum(1 for v in nps if v <= 6)

    def 열(키):
        return [[getattr(r, 키)] if getattr(r, 키) else [] for r in 응답목록]

    진행도표 = 빈도표(열("진행도"), N)
    구매표 = 빈도표(열("구매의향"), N)
    가격표 = 빈도표(열("적정가격"), N)
    버그표 = 빈도표(열("버그경험"), N)

    구 = C.구매선택지
    유료 = sum(찾기(구매표, 구[k])["인원"] for k in ("정가", "의향", "할인"))
    구매의향 = sum(찾기(구매표, 구[k])["인원"] for k in ("정가", "의향"))
    정체 = sum(1 for r in 응답목록 if r.진행도 in C.진행도_정체단계)

    def 응답건수(키):
        return sum(1 for r in 응답목록 if not 무응답(getattr(r, 키)))

    최고 = max((a for a in 육각 if a["평균원값"] is not None), key=lambda a: a["평균원값"], default=None)
    최저 = min((a for a in 육각 if a["평균원값"] is not None), key=lambda a: a["평균원값"], default=None)

    버 = C.버그선택지
    return dict(
        N=N, 육각=육각, 추가=추가,
        육각총평균=반올림(육각총평균, 2) if 육각총평균 is not None else None,
        최고축=최고, 최저축=최저,
        NPS=dict(N=len(nps), 추천=추천, 중립=중립, 비추천=비추천,
                 추천율=백분율(추천, len(nps)), 중립율=백분율(중립, len(nps)),
                 비추천율=백분율(비추천, len(nps)),
                 값=int(반올림((추천 - 비추천) / len(nps) * 100)) if nps else None,
                 평균=반올림(mean(nps), 1) if nps else None),
        진행도=진행도표, 구매의향=구매표, 적정가격=가격표, 버그경험=버그표,
        연령대=빈도표(열("연령대"), N), 성별=빈도표(열("성별"), N),
        선호장르=빈도표([r.선호장르 for r in 응답목록], N),
        진행도정체=dict(인원=정체, 비율=백분율(정체, N)),
        유료고려=dict(인원=유료, 비율=백분율(유료, N)),
        구매의향률=dict(인원=구매의향, 비율=백분율(구매의향, N)),
        버그=dict(진행불가=찾기(버그표, 버["진행불가"])["인원"],
                  지장=찾기(버그표, 버["지장"])["인원"],
                  경미=찾기(버그표, 버["경미"])["인원"],
                  없음=찾기(버그표, 버["없음"])["인원"],
                  지장비율=백분율(찾기(버그표, 버["지장"])["인원"], N)),
        응답률=dict(개선점=응답건수("개선점"), 버그상황=응답건수("버그상황"),
                    개발팀메시지=응답건수("개발팀메시지")),
    )


# ── 문항 집계 ────────────────────────────────────────────────────────────

def 선형배율정의(문항, 코드):
    for d in C.게임_선형배율문항.get(코드, []):
        if 정규화(d["문항"]) == 문항:
            return d
    return None


def 문항유형판정(문항, 답목록, 체크박스, 코드):
    for k, v in C.게임_문항유형.get(코드, {}).items():
        if 정규화(k) == 문항:
            return v
    if 체크박스:
        return "체크박스"
    if 선형배율정의(문항, 코드):
        return "선형배율"
    for k in C.게임_부정선택지.get(코드, {}):
        if 정규화(k) == 문항:
            return "객관식"

    기본 = C.게임_기본문항유형.get(코드)
    if 기본 and 기본 != "자동":
        return 기본

    # '없음' 같은 무응답은 세지 않는다. 세면 답이 두어 종류뿐인 것처럼 보여
    # 서술형이 객관식으로 오인되고 부록 B 에서 원문이 사라진다.
    유효 = [v for v in 답목록 if v and not 무응답(v)]
    if not 유효:
        return "서술형"
    고유 = set(유효)
    if (len(고유) <= C.문항판별["최대선택지수"]
            and max(len(v) for v in 유효) <= C.문항판별["최대답길이"]
            and len(고유) < len(유효)):
        return "객관식"
    return "서술형"


def 문항집계(응답목록, 게임):
    N, 코드 = len(응답목록), 게임["코드"]
    if not N:
        return []
    out = []
    for q, 정의 in enumerate(응답목록[0].고유):
        문항, 체크 = 정의["문항"], 정의["체크박스"]
        원답 = [r.고유[q]["답"] for r in 응답목록]
        값들 = [r.고유[q]["값"] for r in 응답목록]
        서술 = [dict(ID=r.ID, 답=r.고유[q]["답"]) for r in 응답목록 if not 무응답(r.고유[q]["답"])]
        유형 = 문항유형판정(문항, 원답, 체크, 코드)
        항 = dict(문항=문항, 유형=유형, 출처="고유", 순서=q, 통계=None,
                  집계=[] if 유형 == "서술형" else 빈도표(값들, N),
                  서술=서술 if 유형 == "서술형" else [])
        if 유형 == "선형배율":
            d = 선형배율정의(문항, 코드)
            항["통계"] = 축통계([숫자(v) for v in 원답], 문항, d["최소"], d["최대"])
            항["집계"] = [dict(답=str(v), 인원=항["통계"]["분포"].get(v, 0),
                               비율=백분율(항["통계"]["분포"].get(v, 0), N))
                          for v in range(d["최소"], d["최대"] + 1)]
        out.append(항)

    for 키, 라벨 in [("진행도", "진행도"), ("구매의향", "스팀 구매 의향"),
                     ("적정가격", "적정 가격"), ("버그경험", "버그 경험")]:
        모음 = [[getattr(r, 키)] if getattr(r, 키) else [] for r in 응답목록]
        out.append(dict(문항=라벨, 유형="객관식", 출처="공통", 키=키, 통계=None,
                        집계=빈도표(모음, N), 서술=[]))
    return out


def 문항찾기(문항집계목록, 부분):
    for 항 in 문항집계목록:
        if 부분 in 항["문항"]:
            return 항
    return None


