def _플래그(심각도, 규칙, 제목, 근거, 첨부=None):
    return dict(심각도=심각도, 규칙=규칙, 제목=제목, 근거=근거, 첨부=첨부 or [])


def 서술뽑기(응답들, 키, 라벨):
    return [dict(ID=r.ID, 라벨=라벨, 글=getattr(r, 키))
            for r in 응답들 if not 무응답(getattr(r, 키))]


def 플래그판정(지표, 문항집계목록, 응답목록, 게임):
    T, N, 코드 = C.임계값, 지표["N"], 게임["코드"]
    if not N:
        return []
    out = []

    # 규칙 1·2 — 6축 항목 평균
    for i, 축 in enumerate(지표["육각"]):
        if 축["평균"] is None:
            continue
        저점 = [r for r in 응답목록 if r.육각[i] is not None and r.육각[i] <= 2]
        비 = f'1~2점 {축["부정"]}명({백분율(축["부정"], N)}%)'
        if 축["평균원값"] < T["육각평균_Critical"]:
            out.append(_플래그("Critical", "6축평균",
                               f'{축["이름"]} 평균 {축["평균"]:.2f}점 — 8개 항목 최하위권',
                               f'{축["이름"]} {축["평균"]:.2f}점(기준 {T["육각평균_Critical"]}). {비}. '
                               f'진행도가 튜토리얼 단계에 머문 응답자 {지표["진행도정체"]["인원"]}명'
                               f'({지표["진행도정체"]["비율"]}%)과 겹친다.',
                               서술뽑기(저점, "개선점", "개선점")))
        elif 축["평균원값"] < T["육각평균_High"]:
            out.append(_플래그("High", "6축평균",
                               f'{축["이름"]} 평균 {축["평균"]:.2f}점 — 보통(3.0)을 밑돈다',
                               f'{축["이름"]} {축["평균"]:.2f}점(기준 {T["육각평균_High"]}). {비}.',
                               서술뽑기(저점, "개선점", "개선점")))

    # 규칙 1·2·10 확장 — 게임 고유 선형배율
    for 항 in 문항집계목록:
        if 항["유형"] != "선형배율" or not 항["통계"] or 항["통계"]["평균"] is None:
            continue
        st = 항["통계"]
        환산 = (st["평균원값"] - st["최소"]) / (st["최대"] - st["최소"]) * 4 + 1
        저점 = [r for r in 응답목록
                if (v := 숫자(next((c["답"] for c in r.고유 if c["문항"] == 항["문항"]), None))) is not None
                and v <= st["최소"] + 1]
        고점 = [r for r in 응답목록
                if (v := 숫자(next((c["답"] for c in r.고유 if c["문항"] == 항["문항"]), None))) is not None
                and v >= st["최대"]]
        꼬리 = (f' ({st["최소"]}~{st["최대"]}점 척도 · 응답 {st["N"]}명 · '
                f'낮은 쪽 {st["부정"]}명 · 높은 쪽 {st["긍정"]}명)')
        if 환산 < T["육각평균_Critical"]:
            out.append(_플래그("Critical", "고유점수",
                               f'{자르기(항["문항"], 38)} 평균 {st["평균"]:.2f}점',
                               f'평균 {st["평균"]:.2f}점{꼬리}. 기준 {T["육각평균_Critical"]}점을 밑돈다.',
                               서술뽑기(저점, "개선점", "개선점")))
        elif 환산 < T["육각평균_High"]:
            out.append(_플래그("High", "고유점수",
                               f'{자르기(항["문항"], 38)} 평균 {st["평균"]:.2f}점',
                               f'평균 {st["평균"]:.2f}점{꼬리}. 기준 {T["육각평균_High"]}점을 밑돈다.',
                               서술뽑기(저점, "개선점", "개선점")))
        elif 환산 >= T["강점_평균"]:
            out.append(_플래그("강점", "고유점수",
                               f'{자르기(항["문항"], 38)} 평균 {st["평균"]:.2f}점',
                               f'평균 {st["평균"]:.2f}점{꼬리}. 기준 {T["강점_평균"]}점을 넘는다.',
                               서술뽑기(고점, "개발팀메시지", "개발팀에 전하고 싶은 말")))
        if st["표준편차"] is not None and st["표준편차"] >= T["검토필요_표준편차"]:
            out.append(_플래그("검토필요", "고유점수",
                               f'{자르기(항["문항"], 42)} — 응답자별 편차가 크다',
                               f'표준편차 {st["표준편차"]:.2f}{꼬리}. 기준 {T["검토필요_표준편차"]}를 넘는다.',
                               서술뽑기(고점, "개발팀메시지", "고득점자 메시지")
                               + 서술뽑기(저점, "개선점", "저득점자 개선점")))

    # 규칙 10 — 강점
    for i, 축 in enumerate(지표["육각"]):
        if 축["평균"] is None or 축["평균원값"] < T["강점_평균"]:
            continue
        만점 = [r for r in 응답목록 if r.육각[i] == 5]
        out.append(_플래그("강점", "강점",
                           f'{축["이름"]} 평균 {축["평균"]:.2f}점 — 유일하게 기준선을 넘는다'
                           if len([a for a in 지표["육각"] if a["평균원값"] and a["평균원값"] >= T["강점_평균"]]) == 1
                           else f'{축["이름"]} 평균 {축["평균"]:.2f}점',
                           f'{축["이름"]} {축["평균"]:.2f}점. '
                           f'4~5점을 준 응답자가 {축["긍정"]}명({백분율(축["긍정"], N)}%)이고 '
                           f'1~2점은 {축["부정"]}명이다.',
                           서술뽑기(만점, "개발팀메시지", "개발팀에 전하고 싶은 말")))

    # 규칙 11 — 표준편차
    for u, 축 in enumerate(지표["육각"] + 지표["추가"]):
        if 축["표준편차"] is None or 축["표준편차"] < T["검토필요_표준편차"]:
            continue
        idx = u if u < len(지표["육각"]) else None
        키 = None if idx is not None else C.추가축[u - len(지표["육각"])][0]
        점 = (lambda r: r.육각[idx]) if idx is not None else (lambda r: getattr(r, 키))
        고 = [r for r in 응답목록 if 점(r) is not None and 점(r) >= 4]
        저 = [r for r in 응답목록 if 점(r) is not None and 점(r) <= 2]
        out.append(_플래그("검토필요", "표준편차",
                           f'{은는(축["이름"])} 응답자에 따라 평가가 갈린다',
                           f'{축["이름"]} 표준편차 {축["표준편차"]:.2f}(기준 {T["검토필요_표준편차"]}). '
                           f'4~5점 {축["긍정"]}명, 1~2점 {축["부정"]}명으로 양쪽에 몰렸다.',
                           서술뽑기(고, "개발팀메시지", "고득점자 메시지")
                           + 서술뽑기(저, "개선점", "저득점자 개선점")))

    # 규칙 7 — 튜토리얼
    튜 = C.게임_튜토리얼문항.get(코드)
    튜문항 = 정규화(튜["문항"]) if 튜 else None
    if 튜:
        열 = next((i for i, d in enumerate(응답목록[0].고유) if d["문항"] == 튜문항), -1)
        if 열 >= 0:
            어려움 = [r for r in 응답목록 if r.고유[열]["답"] in 튜["어려움"]]
            if len(어려움) / N >= T["튜토리얼어려움"]:
                out.append(_플래그("Critical", "튜토리얼",
                                   f'튜토리얼을 어려워한 응답자가 {len(어려움)}명({백분율(len(어려움), N)}%)이다',
                                   f"""'{"' · '".join(튜["어려움"])}' """
                                   f'{len(어려움)}명 / {N}명({백분율(len(어려움), N)}%, 기준 {int(T["튜토리얼어려움"]*100)}%). '
                                   f'같은 회차에서 진행도가 튜토리얼 단계에 머문 응답자는 '
                                   f'{지표["진행도정체"]["인원"]}명({지표["진행도정체"]["비율"]}%)이다.',
                                   서술뽑기(어려움, "개선점", "개선점")))

    # 규칙 8 — 진행도 정체
    if 지표["진행도정체"]["인원"] / N >= T["진행도정체"]:
        정체자 = [r for r in 응답목록 if r.진행도 in C.진행도_정체단계]
        단계 = " 또는 ".join("'" + x + "'" for x in C.진행도_정체단계)
        out.append(_플래그("Critical", "진행도",
                           f'{지표["진행도정체"]["인원"]}명({지표["진행도정체"]["비율"]}%)이 본편에 진입하지 못했다',
                           f'진행도가 {단계}에 머문 응답자 '
                           f'{지표["진행도정체"]["인원"]}명 / {N}명'
                           f'({지표["진행도정체"]["비율"]}%, 기준 {int(T["진행도정체"]*100)}%).',
                           서술뽑기(정체자, "개선점", "개선점")
                           + 서술뽑기(정체자, "개발팀메시지", "개발팀에 전하고 싶은 말")))

    # 규칙 5·6 — 버그
    버 = C.버그선택지
    if 지표["버그"]["진행불가"] >= T["진행불가버그_건수"]:
        해당 = [r for r in 응답목록 if r.버그경험 == 버["진행불가"]]
        out.append(_플래그("Critical", "버그",
                           f"진행이 불가능한 버그가 {지표['버그']['진행불가']}건 보고됐다",
                           f"'{버['진행불가']}' {지표['버그']['진행불가']}명 / {N}명"
                           f"({백분율(지표['버그']['진행불가'], N)}%). 아래 상황 서술을 그대로 옮겼다.",
                           서술뽑기(해당, "버그상황", "버그 상황")))
    if 지표["버그"]["지장"] / N >= T["지장버그_High"]:
        해당 = [r for r in 응답목록 if r.버그경험 == 버["지장"]]
        안정 = 지표["추가"][1]["평균"]
        out.append(_플래그("High", "버그",
                           f'플레이에 지장을 준 버그를 {지표["버그"]["지장"]}명({지표["버그"]["지장비율"]}%)이 겪었다',
                           f"'{버['지장']}' {지표['버그']['지장']}명 / {N}명({지표['버그']['지장비율']}%, "
                           f"기준 {int(T['지장버그_High']*100)}%). 기술 안정성 점수는 "
                           f"{f'{안정:.2f}' if 안정 is not None else '-'}점으로 낮지 않다.",
                           서술뽑기(해당, "버그상황", "버그 상황")))

    # 규칙 9 — NPS 비추천
    if 지표["NPS"]["N"] and 지표["NPS"]["비추천"] / 지표["NPS"]["N"] >= T["NPS비추천_High"]:
        해당 = [r for r in 응답목록 if isinstance(r.추천의향, (int, float)) and r.추천의향 <= 6]
        out.append(_플래그("High", "NPS",
                           f'비추천(0~6점) 응답자가 {지표["NPS"]["비추천"]}명({지표["NPS"]["비추천율"]}%)이다',
                           f'NPS {지표["NPS"]["값"]}. 비추천 {지표["NPS"]["비추천"]}명 · '
                           f'중립 {지표["NPS"]["중립"]}명 · 추천 {지표["NPS"]["추천"]}명'
                           f'(기준 비추천 {int(T["NPS비추천_High"]*100)}%).',
                           서술뽑기(해당, "개선점", "개선점")))

    # 규칙 3·4 — 부정 선택지 응답률
    부정정규 = {정규화(k): v for k, v in C.게임_부정선택지.get(코드, {}).items()}
    for 항 in 문항집계목록:
        if 항["출처"] == "고유":
            if 튜문항 and 항["문항"] == 튜문항:
                continue                       # 튜토리얼 전용 규칙과 중복
            부정 = 부정정규.get(항["문항"])
        elif 항.get("키") in C.공통_부정선택지:
            if 항["키"] == "진행도":
                continue                       # 진행도 전용 규칙과 중복
            부정 = C.공통_부정선택지[항["키"]]
        else:
            부정 = None
        if not 부정:
            continue

        for 선택지 in 부정:
            인원 = 찾기(항["집계"], 선택지)["인원"]
            if not 인원 or 인원 / N < T["부정선택지_High"]:
                continue
            심각 = "Critical" if 인원 / N >= T["부정선택지_Critical"] else "High"
            if 항["출처"] == "고유":
                고른 = [r for r in 응답목록
                        if 선택지 in next((c["값"] for c in r.고유 if c["문항"] == 항["문항"]), [])]
            else:
                고른 = [r for r in 응답목록 if getattr(r, 항["키"]) == 선택지]
            out.append(_플래그(심각, "부정선택지",
                               f"""{자르기(항["문항"], 44)} — '{자르기(선택지, 26)}' {백분율(인원, N)}%""",
                               f"'{선택지}'를 고른 응답자 {인원}명 / {N}명"
                               f"({백분율(인원, N)}%, 기준 {int(T['부정선택지_High']*100)}%). "
                               f"나머지 {N - 인원}명은 다른 선택지를 골랐다.",
                               서술뽑기(고른, "개선점", "개선점")))

    순위 = {"Critical": 0, "High": 1, "검토필요": 2, "강점": 3}
    out.sort(key=lambda f: 순위.get(f["심각도"], 9))
    return out


# ── 서술 모음 (부록 B) ───────────────────────────────────────────────────

def 서술모음(응답목록, 문항집계목록):
    out = []
    for 항 in 문항집계목록:
        if 항["출처"] == "고유" and 항["유형"] == "서술형" and 항["서술"]:
            out.append(dict(라벨=항["문항"], 출처="고유", 건수=len(항["서술"]),
                            항목=[dict(ID=s["ID"], 글=s["답"]) for s in 항["서술"]]))
    for 키, 라벨 in [("개선점", "현재 빌드에서 수정 · 개선되었으면 하는 점"),
                     ("버그상황", "버그 · 오류 발생 상황"),
                     ("개발팀메시지", "개발팀에 전하고 싶은 말")]:
        항목 = [dict(ID=r.ID, 글=getattr(r, 키)) for r in 응답목록 if not 무응답(getattr(r, 키))]
        out.append(dict(라벨=라벨, 출처="공통", 건수=len(항목), 항목=항목))
    return out


# ── 한 게임 통째로 ───────────────────────────────────────────────────────

def 게임집계(응답목록, 게임):
    지표 = 지표계산(응답목록)
    문항 = 문항집계(응답목록, 게임)
    return dict(게임=게임, 응답=응답목록, 지표=지표, 문항집계=문항,
                세그먼트=세그먼트(응답목록, 게임),
                플래그=플래그판정(지표, 문항, 응답목록, 게임),
                서술모음=서술모음(응답목록, 문항))
