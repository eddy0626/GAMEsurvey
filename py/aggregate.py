def 반올림(x, 자리=0):
    if x is None:
        return None
    f = 10 ** 자리
    v = x * f
    v = -((-v) // 1 + (0.5 <= ((-v) % 1))) if v < 0 else (v // 1 + (0.5 <= (v % 1)))
    return v / f


def 백분율(n, N):
    return int(반올림(n / N * 100)) if N else 0


def 축통계(값들, 이름, 최소=1, 최대=5):
    유효 = [v for v in 값들 if isinstance(v, (int, float)) and not isinstance(v, bool)]
    분포 = {v: 0 for v in range(최소, 최대 + 1)}
    for v in 유효:
        if v in 분포:
            분포[v] += 1
    긍정 = sum(분포.get(v, 0) for v in range(max(최소, 최대 - 1), 최대 + 1))
    부정 = sum(분포.get(v, 0) for v in range(최소, min(최대, 최소 + 1) + 1))
    m = mean(유효) if 유효 else None
    sd = stdev(유효) if len(유효) >= 2 else None
    return dict(이름=이름, N=len(유효), 최소=최소, 최대=최대,
                평균=반올림(m, 2) if m is not None else None, 평균원값=m,
                표준편차=반올림(sd, 2) if sd is not None else None,
                긍정=긍정, 부정=부정, 분포=분포)


def 빈도표(값들의목록, N):
    맵, 순서 = Counter(), []
    for 값들 in 값들의목록:
        for v in 값들:
            if v not in 맵:
                순서.append(v)
            맵[v] += 1
    out = [dict(답=k, 인원=맵[k], 비율=백분율(맵[k], N)) for k in 순서]
    out.sort(key=lambda d: -d["인원"])          # 파이썬 sort 는 안정 정렬
    return out


def 찾기(표, 답):
    for row in 표:
        if row["답"] == 답:
            return row
    return dict(답=답, 인원=0, 비율=0)


