# -*- coding: utf-8 -*-
"""담당자 체크리스트 (마크다운)

docx 본문에서 뺀 안내 · 초안 · 판단이 필요한 자리를 여기 모은다.
문서는 그대로 개발사에 나갈 수 있는 상태로 두고, 담당자가 할 일은 이 파일만 본다.
"""
import os

from . import config as C
from .aggregate import 백분율, 찾기
from .kor import 은는, 이가

_심각도순 = {"Critical": 0, "High": 1, "검토필요": 2, "강점": 3}


def 만들기(집계, 경로, 리포트파일, 카드수):
    게임, 지표 = 집계["게임"], 집계["지표"]
    N = 지표["N"]
    L = []
    A = L.append

    A(f'# {게임["게임명"]} — 담당자 체크리스트')
    A("")
    A(f'개발사 {게임["개발사"]} · 응답 {N}명 · 리포트 `{리포트파일}` · 개별 카드 {카드수}건')
    A("")
    A("이 파일은 내부용이다. 개발사에 나가는 것은 docx 두 종류뿐이다.")
    A("")

    if not N:
        A("응답이 없어 집계할 내용이 없다.")
        _쓰기(경로, L)
        return 경로

    # ── 1. 결론 세 줄 ──
    A("## 1. 결론 세 줄 확정")
    A("")
    A("리포트 첫 장 '요약' 에 들어간 세 줄이다. 수치에서 뽑은 것이라 그대로 두면 밋밋하다.")
    A("무엇이 문제이고 무엇을 지켜야 하는지 한 줄씩 다시 쓰는 편이 낫다.")
    A("")
    최고, 최저 = 지표["최고축"], 지표["최저축"]
    if 최고:
        A(f'- 현재: {이가(최고["이름"])} {최고["평균"]:.2f}점으로 가장 높다.')
    if 최저:
        A(f'- 현재: {이가(최저["이름"])} {최저["평균"]:.2f}점으로 가장 낮다.')
    A(f'- 현재: NPS {지표["NPS"]["값"]}, 유료 구매 고려 {지표["유료고려"]["비율"]}%.')
    A("")
    A("확정본")
    A("")
    A("1. ")
    A("2. ")
    A("3. ")
    A("")

    # ── 2. 이슈 후보 ──
    플래그 = sorted(집계["플래그"], key=lambda f: _심각도순.get(f["심각도"], 9))
    A(f"## 2. 이슈 후보 {len(플래그)}건 — 채택 여부와 권고")
    A("")
    A("규칙이 임계값으로 뽑은 후보다. 무엇이 걸렸는지까지만 알려 준다.")
    A("리포트에 남길 것을 고르고, 권고 문장을 써서 docx 3장의 빈 '권고' 칸에 옮긴다.")
    A("올리지 않을 항목은 docx 에서 해당 카드를 지운다.")
    A("")
    for i, f in enumerate(플래그):
        A(f'### F{i+1}  [{f["심각도"]}]  {f["제목"]}')
        A("")
        A(f'근거 · {f["근거"]}')
        A("")
        if f["첨부"]:
            ids = []
            for a in f["첨부"]:
                if a["ID"] not in ids:
                    ids.append(a["ID"])
            A(f'인용 {len(f["첨부"])}건 · 관련 응답자 {" ".join(ids)}')
            A("")
            for a in f["첨부"][:6]:
                글 = a["글"].replace("\n", " ").strip()
                A(f'  - {a["ID"]} ({a.get("라벨", "")}) {글}')
            if len(f["첨부"]) > 6:
                A(f'  - 외 {len(f["첨부"]) - 6}건 (리포트 부록 B 참고)')
            A("")
        A("- [ ] 리포트에 올린다")
        A("- 권고: ")
        A("")

    # ── 3. 시기 배분 ──
    A("## 3. 5장 시기 배분")
    A("")
    A("심각도로 자동 배치한 초안이다. 개발사 사정에 맞게 옮긴다.")
    A("")
    시기 = {"Critical": "다음 빌드", "High": "단기", "검토필요": "중기", "강점": "유지"}
    for i, f in enumerate(플래그):
        if f["심각도"] == "강점":
            continue
        A(f'- [ ] F{i+1} — {시기.get(f["심각도"], "중기")} — {f["제목"]}')
    A("")

    # ── 4. 임계값 점검 ──
    수 = {}
    for f in 플래그:
        수[f["심각도"]] = 수.get(f["심각도"], 0) + 1
    A("## 4. 임계값 점검")
    A("")
    A(f'이번 판정 — Critical {수.get("Critical", 0)} · High {수.get("High", 0)} · '
      f'검토필요 {수.get("검토필요", 0)} · 강점 {수.get("강점", 0)}  (합계 {len(플래그)})')
    A("")
    if len(플래그) > 10:
        A("한 게임에 10건이 넘는다. 임계값이 느슨하다는 뜻이므로 `py/config.py` 의 `임계값` 을 올린다.")
    elif len(플래그) <= 2:
        A("2건 이하다. 임계값이 빡빡하다는 뜻이므로 `py/config.py` 의 `임계값` 을 내린다.")
    else:
        A("적정 범위(3~10건)다. 그대로 둔다.")
    A("")

    # ── 5. 발송 전 확인 ──
    A("## 5. 발송 전 확인")
    A("")
    A("- [ ] 3장에서 올리지 않을 항목의 카드를 지웠다")
    A("- [ ] 3장 각 항목의 '권고' 칸을 채웠다")
    A("- [ ] 첫 장 '요약' 세 줄을 확정본으로 바꿨다")
    A("- [ ] 5장 표의 '구체 작업 · 기대 효과' 칸을 채웠다")
    A("- [ ] 부록 B 서술 원문에 실명 · 연락처가 섞이지 않았다")
    A("- [ ] 개별 카드를 어디까지 전달할지 정했다 (개발사 / 참여자 본인 / 내부 보관)")
    A("- [ ] PDF 로 내보냈다")
    A("")
    A("---")
    A("")
    A(f'생성 기준 — 응답 {N}명 · 문항 {len(집계["응답"][0].고유)}개(게임 고유) + 공통 22개')

    _쓰기(경로, L)
    return 경로


def _쓰기(경로, 줄들):
    os.makedirs(os.path.dirname(경로), exist_ok=True)
    with open(경로, "w", encoding="utf-8") as fp:
        fp.write("\n".join(줄들) + "\n")


def 파일명():
    return "담당자_체크리스트.md"
