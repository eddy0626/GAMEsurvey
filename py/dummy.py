def _고르기(rnd, 후보, 성향):
    목록 = 후보[성향] if isinstance(후보, dict) else 후보
    return rnd.choice(목록)


def _객관식답(rnd, q, 성향):
    """성향이 나쁠수록 선택지 목록의 앞쪽(부정 쪽)을 고르게 한다.
    survey_data 의 선택지는 대부분 부정 → 긍정 오름차순으로 정돈돼 있다."""
    옵 = list(q["options"])
    n = len(옵)
    if n == 1:
        return 옵[0]
    가중 = []
    for i, o in enumerate(옵):
        위치 = i / (n - 1)                      # 0=맨앞(부정) 1=맨뒤(긍정)
        if 성향 == 0:
            w = 0.2 + 위치 * 2.4
        elif 성향 == 1:
            w = 1.0 + (1 - abs(위치 - 0.5) * 2) * 1.2
        else:
            w = 2.6 - 위치 * 2.4
        가중.append(max(w, 0.05))
    return rnd.choices(옵, weights=가중, k=1)[0]


def _체크박스답(rnd, q, 성향):
    옵 = list(q["options"])
    n = min(len(옵), rnd.choice([1, 2, 2, 3]))
    가중 = []
    for i, o in enumerate(옵):
        위치 = i / max(len(옵) - 1, 1)
        가중.append(max((0.3 + 위치 * 2.2) if 성향 == 0 else
                        (1.0) if 성향 == 1 else (2.4 - 위치 * 2.0), 0.05))
    고른 = []
    후보 = 옵[:]
    가중2 = 가중[:]
    for _ in range(n):
        if not 후보:
            break
        c = rnd.choices(후보, weights=가중2, k=1)[0]
        i = 후보.index(c)
        고른.append(c)
        후보.pop(i); 가중2.pop(i)
    return ", ".join(고른)


def _선형답(rnd, q, 성향):
    lo, hi = q["bounds"]
    폭 = hi - lo
    if 성향 == 0:
        v = hi - rnd.choice([0, 0, 1])
    elif 성향 == 1:
        v = lo + round(폭 * 0.5) + rnd.choice([-1, 0, 0, 1])
    else:
        v = lo + rnd.choice([0, 1, 1])
    return max(lo, min(hi, v))


def _서술답(rnd, 폼번호, q, 성향, 사람):
    풀 = 서술풀[폼번호]
    t = q["text"]
    if "불합리" in t and "불합리" in 풀.get("고유서술", {}):
        return _고르기(rnd, 풀["고유서술"]["불합리"], 성향)
    if "직업" in t:
        return rnd.choice(["주술사", "백기사", "사제", "주술사", "백기사"])
    # 30% 는 '없음' — 실제 응답에서 흔한 패턴이고, 자동 유형 판별의 함정이기도 하다
    if rnd.random() < 0.30:
        return rnd.choice(["없음", "없음", ""])
    return rnd.choice([_긴서술[성향],
                       _고르기(rnd, 풀["개선점"], 성향),
                       _긴서술[성향]])


def 폼별응답(폼, 인원=16, seed=None):
    """한 폼의 (헤더, 행들) 생성"""
