def 전체생성(폴더, 인원=16):
    """5개 폼의 응답 CSV 를 만든다. 구글 시트에서 내려받은 것과 같은 모양."""
    os.makedirs(폴더, exist_ok=True)
    만든것 = []
    for 폼 in FORMS:
        헤더, 행들 = 폼별응답(폼, 인원)
        경로 = os.path.join(폴더, f'{폼["no"]}_{폼["game"].replace(":", "：").replace("/", "／")}.csv')
        with open(경로, "w", encoding="utf-8-sig", newline="") as fp:
            w = csv.writer(fp)
            w.writerow(헤더)
            w.writerows(행들)
        만든것.append((폼["no"], 폼["game"], 경로, len(헤더), len(행들)))
    return 만든것


