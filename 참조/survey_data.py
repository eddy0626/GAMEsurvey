# 폼 전체 연속번호 부여
#   응답자에게는 1, 2, 3 … 으로 끊김 없이 보이고,
#   문서에는 내부 ID(A1 · Q1 · C1)를 함께 남겨 출처를 추적한다.
# ─────────────────────────────────────────────────────────────
def numbered(form):
    """[(섹션, [(표시번호, 문항), ...]), ...] 반환. 파일업로드 문항도 번호를 차지한다."""
    secs = SECTIONS_PRE + list(form["sections"]) + SECTIONS_POST
    n = 0
    out = []
    for sec in secs:
        rows = []
        for q in sec["questions"]:
            n += 1
            rows.append((n, q))
        out.append((sec, rows))
    return out


def number_range(form, which):
    """which: 'pre' | 'company' | 'post' → (시작번호, 끝번호)"""
    blocks = numbered(form)
    npre, npost = len(SECTIONS_PRE), len(SECTIONS_POST)
    if which == "pre":
        rows = [r for b in blocks[:npre] for r in b[1]]
    elif which == "post":
        rows = [r for b in blocks[-npost:] for r in b[1]]
    else:
        rows = [r for b in blocks[npre:-npost] for r in b[1]]
    return rows[0][0], rows[-1][0]


def total_questions(form):
    return sum(len(rows) for _, rows in numbered(form))
